import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
test('REST, GraphQL, realtime delivery and accessible insight table use the actual API',async({page})=>{
 await page.goto('/');
 await page.getByLabel('Email',{exact:true}).fill('synthetic-'+randomUUID()+'@example.test');
 await page.getByLabel('Password',{exact:true}).fill('synthetic-course-password-2026');
 await page.getByRole('button',{name:'Sign up',exact:true}).click();
 await expect(page.getByRole('button',{name:'Log out',exact:true})).toBeVisible();
 await page.getByLabel('Title',{exact:true}).fill('Browser verified note');
 await page.getByLabel('Observation',{exact:true}).fill('A synthetic observation.');
 await page.getByRole('button',{name:'Save note',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Browser verified note',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'GraphQL',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Browser verified note',exact:true})).toBeVisible();
 await page.getByLabel('Title',{exact:true}).fill('GraphQL verified note');
 await page.getByLabel('Observation',{exact:true}).fill('One shared repository.');
 await page.getByRole('button',{name:'Save note',exact:true}).click();
 await expect(page.getByRole('heading',{name:'GraphQL verified note',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Live',exact:true}).click();
 await expect(page.getByRole('status')).toHaveText('Connected');
 await page.getByLabel('Title',{exact:true}).fill('Live verified note');
 await page.getByLabel('Observation',{exact:true}).fill('Confirmed after persistence.');
 await page.getByRole('button',{name:'Save note',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Live verified note',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Insights',exact:true}).click();
 await expect(page.getByRole('table')).toBeVisible();
 await expect(page.getByText('3 total notes. Counts describe this synthetic demo only.')).toBeVisible();
});
test('Next server actions create/delete and SSR renders the same public note in initial HTML',async({page,request})=>{
 await page.goto('http://127.0.0.1:3001');
 await page.getByLabel('Email',{exact:true}).fill('next-'+randomUUID()+'@example.test');
 await page.getByLabel('Password',{exact:true}).fill('synthetic-course-password-2026');
 await page.getByRole('button',{name:'Sign up',exact:true}).click();
 await expect(page.getByRole('button',{name:'Log out',exact:true})).toBeVisible();
 await page.getByLabel('Title',{exact:true}).fill('Next boundary verified');
 await page.getByLabel('Observation',{exact:true}).fill('A server action forwards validated input.');
 await page.getByRole('button',{name:'Save note',exact:true}).click();
 await expect(page.getByText('Note saved.',{exact:true})).toBeVisible();
 const ssr=await request.get('http://127.0.0.1:5174');
 expect(await ssr.text()).toContain('Next boundary verified');
 await page.getByRole('link',{name:'Next boundary verified',exact:true}).click();
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href',/\/notes\//);
 await page.getByRole('button',{name:'Delete my note',exact:true}).click();
 await expect(page.getByText('Note deleted.',{exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'Next boundary verified',exact:true})).toHaveCount(0);
});
